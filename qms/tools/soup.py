"""Generate qms/soup.md, the IEC 62304 SOUP register, from Cargo.lock.

SOUP here is every third-party crate compiled into the released `opengrowth`
binary: the normal and build dependencies of opengrowth-cli, transitively.
Dev-only dependencies (tests, benchmarks) are excluded.

    python3 -I qms/tools/soup.py            write qms/soup.md
    python3 -I qms/tools/soup.py --check    exit 1 if qms/soup.md is out of date
"""

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "qms" / "soup.md"
RELEASED = "opengrowth-cli"


def main() -> int:
    metadata = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--format-version", "1", "--locked", "--offline"],
            cwd=ROOT, capture_output=True, text=True, check=True,
        ).stdout
    )
    packages = {p["id"]: p for p in metadata["packages"]}
    workspace = set(metadata["workspace_members"])
    nodes = {n["id"]: n for n in metadata["resolve"]["nodes"]}

    root = next(i for i in workspace if packages[i]["name"] == RELEASED)
    seen, stack = set(), [root]
    while stack:
        current = stack.pop()
        if current in seen:
            continue
        seen.add(current)
        for dep in nodes[current]["deps"]:
            kinds = {k["kind"] for k in dep["dep_kinds"]}
            if kinds - {"dev"}:
                stack.append(dep["pkg"])

    rows = sorted(
        (packages[i] for i in seen if i not in workspace),
        key=lambda p: (p["name"], p["version"]),
    )
    # REUSE-IgnoreStart: these are the header of the generated file, not of this script.
    lines = [
        "<!-- SPDX-FileCopyrightText: 2026 Open Health Technology Foundation contributors -->",
        "<!-- SPDX-License-Identifier: CC-BY-SA-4.0 -->",
        # REUSE-IgnoreEnd
        "",
        "# SOUP register",
        "",
        "Software of unknown provenance (IEC 62304): every third-party crate compiled into the released `opengrowth` binary. **Generated by `s/soup` from `Cargo.lock`; do not edit by hand.** CI fails if it is out of date.",
        "",
        "Licences, security advisories, and sources are checked on every push by `cargo deny` (`deny.toml`). Each release reviews the diff of this file ([procedures.md](procedures.md#suppliers-and-soup)). Platform-specific crates (for example for Windows) are listed whether or not they are built on a given platform.",
        "",
        f"{len(rows)} crates.",
        "",
        "| Crate | Version | Licence | Source | Repository |",
        "| --- | --- | --- | --- | --- |",
    ]
    for p in rows:
        source = "crates.io" if (p.get("source") or "").startswith("registry+") else (p.get("source") or "local")
        repository = p.get("repository") or ""
        lines.append(f"| {p['name']} | {p['version']} | {p.get('license') or 'unspecified'} | {source} | {repository} |")
    text = "\n".join(lines) + "\n"

    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            print("qms/soup.md is out of date; run s/soup and commit the result", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows)} crates)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
